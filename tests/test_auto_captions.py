# group: network
"""Auto-captions for real: labels, then inside / separate file / burned in on a 20 s clip."""
import json, shutil, subprocess, sys, types
from pathlib import Path
from helpers import WORK  # grabF on the path, settings in a temp folder
import app
SC = WORK
OUT = SC / "autosubs"
shutil.rmtree(OUT, ignore_errors=True)
app.HISTORY = SC / "cfg21" / "history.json"
ok = lambda c, m: print(("PASS " if c else "FAIL ") + m, flush=True)
U = "https://www.youtube.com/watch?v=dQw4w9WgXcQ"
app.WINDOW = types.SimpleNamespace(get_current_url=lambda: "http://127.0.0.1:1/i", real_url="http://127.0.0.1:1/i")
app.load_settings = lambda: dict(app.DEFAULTS)
info = app.Api().probe.__wrapped__(app.Api(), U)["info"]
ok(info["subs"][0] == {"id": "en", "label": "English"}, f"uploader subtitles: {[s['label'] for s in info['subs']]}")
ok(info["autosubs"] == [{"id": "auto:en-orig", "label": "English (auto-generated by youtube)"}], f"auto-generated: {info['autosubs']}")
fr = next((s for s in info["autotrans"] if s["id"] == "auto:fr"), None)
ok(fr and fr["label"] == "French (auto-translated by youtube)", f"auto-translated ({len(info['autotrans'])}), e.g. {fr}")

ev = []
app.push = lambda e, d: ev.append((e, d))
FP = app.ffmpeg_exe("ffprobe")


def run(mode, folder, style="clean"):
    ev.clear()
    req = app.clean_request({"url": U, "mode": "video", "quality": 720, "subs": "auto:en-orig", "subs_mode": mode,
                             "sub_style": style, "clip": [43, 63]})
    app.Job("a" + mode, req, {**app.DEFAULTS, "out": str(OUT / folder)}).run()
    return ev[-1]


# inside the video
e, d = run("embed", "inside")
f = Path(d["files"][0]) if e == "done" else None
streams = json.loads(subprocess.run([FP, "-v", "quiet", "-print_format", "json", "-show_streams", str(f)], capture_output=True,
                                    text=True, encoding="utf-8").stdout)["streams"] if f else []
sub = [s for s in streams if s["codec_type"] == "subtitle"]
ok(e == "done" and sub and sub[0].get("tags", {}).get("title") == "English (auto-generated by youtube)"
   and sorted(p.name for p in f.parent.iterdir()) == [f.name],
   f"inside: track named {sub[0].get('tags', {}).get('title') if sub else '-'}; folder {sorted(p.name for p in f.parent.iterdir()) if f else d}")

# separate file: clean one-line-at-a-time captions, lined up with the clip
e, d = run("file", "file")
srt = next((OUT / "file").glob("*.srt"), None)
text = srt.read_text(encoding="utf-8") if srt else ""
cues = [c for c in text.strip().split("\n\n") if c]
first = cues[0].splitlines() if cues else []
ok(srt and srt.name.endswith(".en.auto.srt"), f"file name says it's automatic: {srt.name if srt else '-'}")
ok(len(cues) > 3 and first[1].startswith("00:00:0") and all(len(c.splitlines()) == 3 for c in cues),
   f"{len(cues)} clean cues, one line each, starting at {first[1] if first else '-'}")
print("   first lines:", [c.splitlines()[2] for c in cues[:4]])

# burned in
e, d = run("burn", "burn", "boxed")
f = Path(d["files"][0]) if e == "done" else None
ok(e == "done" and f.suffix == ".mp4" and sorted(p.name for p in f.parent.iterdir()) == [f.name], f"burned: {f.name if f else d}")
if f:
    subprocess.run([app.ffmpeg_exe(), "-y", "-loglevel", "error", "-ss", "4.6", "-i", str(f), "-frames:v", "1",
                    "-vf", "crop=iw*0.75:ih*0.4:iw*0.125:ih*0.6,scale=720:-1", str(OUT / "burn.png")])
